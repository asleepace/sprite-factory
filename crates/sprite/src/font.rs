pub const GLYPH_W: usize = 6; // 5 + 1 spacing
pub const GLYPH_H: usize = 7;

#[allow(clippy::too_many_arguments)]
/// Draw `text` into an RGB buffer of width `w` at (x, y), each font pixel `scale`×`scale`.
pub fn draw_text(buf: &mut [u8], w: usize, h: usize, x: usize, y: usize, text: &str, scale: usize, color: [u8; 3]) {
    let mut cx = x;
    for ch in text.chars() {
        let up = ch.to_ascii_uppercase();
        if let Some((_, rows)) = GLYPHS.iter().find(|(c, _)| *c == up) {
            for (ry, bits) in rows.iter().enumerate() {
                for rx in 0..5 {
                    if bits & (1 << (4 - rx)) != 0 {
                        for sy in 0..scale {
                            for sx in 0..scale {
                                let (px, py) = (cx + rx * scale + sx, y + ry * scale + sy);
                                if px < w && py < h {
                                    buf[(py * w + px) * 3..(py * w + px) * 3 + 3].copy_from_slice(&color);
                                }
                            }
                        }
                    }
                }
            }
        }
        cx += GLYPH_W * scale;
    }
}

pub fn text_width(text: &str, scale: usize) -> usize {
    text.chars().count() * GLYPH_W * scale
}
